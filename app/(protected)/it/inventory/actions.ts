"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { requirePermission } from "@/lib/auth/require-permission";
import { logAuditEvent } from "@/lib/audit/log";

export type AssetFormState = { error: string | null };

function text(formData: FormData, field: string) {
  return String(formData.get(field) ?? "").trim();
}

function optionalText(formData: FormData, field: string) {
  return text(formData, field) || null;
}

// Returns errors as state (useActionState) instead of throwing: in production Next.js hides a
// thrown Server Action error's message, so "serial number already exists" would otherwise
// reach the user as a generic error page.
export async function createAsset(
  _prevState: AssetFormState,
  formData: FormData,
): Promise<AssetFormState> {
  const { supabase, personId, actorLabel } = await requirePermission("it.assets.create");

  const assetName = text(formData, "asset_name");
  const serialNumber = text(formData, "serial_number");
  const assetTypeId = text(formData, "asset_type_id");
  const companyId = text(formData, "company_id");
  if (!assetName || !serialNumber || !assetTypeId || !companyId) {
    return { error: "Asset name, type, serial number and company are required." };
  }

  const purchaseDate = optionalText(formData, "purchase_date");
  const warrantyExpiry = optionalText(formData, "warranty_expiry");
  if (purchaseDate && warrantyExpiry && warrantyExpiry < purchaseDate) {
    return { error: "Warranty expiry can't be before the purchase date." };
  }

  const { data: assetType } = await supabase
    .schema("it")
    .from("asset_types")
    .select("is_active")
    .eq("id", assetTypeId)
    .maybeSingle();
  if (!assetType?.is_active) return { error: "Choose an active asset type." };

  // asset_tag is generated by the database (it.next_number) and status defaults to Unassigned;
  // neither is accepted from the form.
  const { data: asset, error } = await supabase
    .schema("it")
    .from("assets")
    .insert({
      asset_name: assetName,
      serial_number: serialNumber,
      asset_type_id: assetTypeId,
      company_id: companyId,
      site_id: optionalText(formData, "site_id"),
      manufacturer: optionalText(formData, "manufacturer"),
      model_number: optionalText(formData, "model_number"),
      purchase_date: purchaseDate,
      condition: optionalText(formData, "condition"),
      warranty_expiry: warrantyExpiry,
      notes: optionalText(formData, "notes"),
      created_by: personId,
      updated_by: personId,
    })
    .select("asset_tag")
    .single();
  // 23505 = unique_violation: uq_assets_serial_live (serial already on a non-deleted asset).
  if (error?.code === "23505") {
    return { error: `An asset with serial number "${serialNumber}" already exists.` };
  }
  if (error) return { error: error.message };

  // audit_log's insert policy is currently admin-only (0004), so this records nothing for
  // non-admin IT staff — see 07-it-inventory-plan.md §8 (4b).
  await logAuditEvent({
    supabase,
    actorId: personId,
    actorLabel,
    module: "it",
    action: "CREATED",
    details: `Registered asset ${asset.asset_tag} (${assetName}, serial ${serialNumber})`,
  });

  revalidatePath("/it/inventory");
  redirect(`/it/inventory?created=${encodeURIComponent(asset.asset_tag)}`);
}
